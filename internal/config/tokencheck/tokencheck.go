// Package tokencheck validates user color-token overrides (GDK-769 wave,
// GDK-785) with the same color math tools/theme-check.mjs asserts the shipped
// palettes with at build time. User colors arrive at runtime, where the build
// gate cannot see them; this package is the write-time gate and the
// load-time warning source for that surface.
//
// Severity policy (user decision 2026-08-25: "난 대비는 워닝만 떠야지
// 거절은 아니라고 생각해. 대비 뿐 아니라 전반적으로" — judgment warns, only
// machine-checkable conditions refuse): a violation REFUSES when, and only
// when, a machine can see it without taste — a value that cannot parse
// (non-hex color). Everything judgment-shaped — tier, contrast, ΔEok,
// deuteranopia — WARNS and the value is carried: the look is the user's, and
// live filming measured agents burning turns working around refusals. The
// measurements stay in every warning (the diagnostics are unchanged; only
// the verdict moved), and the message teaches the next move instead of
// blocking it.
//
// The two implementations are pinned together by golden vectors:
// tools/theme-check.mjs --emit-vectors writes
// testdata/token-vectors.json from the exact formulas below, and the tests
// consume the full file. A formula that drifts here shows up as a vector
// mismatch, not as a silently different acceptance boundary.
//
// Tier policy (single source: the embedded catalog.json, generated by
// tools/token-catalog.mjs from web/src/app.css — GDK-787):
//
//	locked     10 tokens — grounds (bg-*), text tiers, search-match, shell.
//	           Overrides WARN and save; palette authoring stays
//	           the recommendation (custom-palette scope, GDK-789).
//	validated  12 tokens — accent 4, border 2, status inks 5, focus-ring.
//	           Open for override, judged at write time by the rules below
//	           (warn, not refuse).
//	free       22 tokens — lozenge/avatar/dept chips, scrim, scrollbar-hover.
//	           Any valid hex passes.
//
// Rule derivations — every floor is a current theme-check assertion, carried
// over verbatim (no floor is invented in this package):
//
//	status-pair               pairwise status-ink ΔEok ≥ 0.05
//	                          (theme-check.mjs PAIR_N, checkPairwise)
//	status-pair-deuteranopia  the same pairs after the Machado 2009
//	                          severity-1.0 simulation, ΔEok ≥ 0.04
//	                          (theme-check.mjs PAIR_D, DEUT_M — the matrix
//	                          must not be substituted or transposed)
//	status-role-floor         overridden status ink on each ground:
//	                          ≥ 4.5 on bg-base/panel/elevated (text role),
//	                          ≥ 3 on bg-hover/active (dot role), compared at
//	                          two-decimal rounding like theme-check cr()
//	                          ("status ink floors" + "per-role ink contrast
//	                          floors" sections)
//	accent-text-contrast      accent-text on accent-subtle and on each
//	                          ground ≥ 4.5 — the text-role floor theme-check
//	                          applies to ink-on-ground pairs, applied to the
//	                          surfaces accent-text is actually painted on
//	                          (badges on accent-subtle, keys and links on the
//	                          grounds; measured: every shipped palette clears
//	                          it on all six, minimum 5.27)
//
// Deliberate narrowing (three-part justification, per the GDK-769
// investigation Q2 recommendation adopted 2026-08-24): theme-check also holds
// status-ink loudness RANK invariant across palettes (its "rank" section).
// The runtime does not require rank of an override — rank is taste, not
// legibility; the build assertion stays in force for app.css palettes. Same
// formulas and same thresholds are kept everywhere rank IS legibility.
//
// For accent, accent-hover, accent-subtle, border-subtle, border-strong and
// focus-ring, theme-check carries no named assertion today, so no floor is
// carried for them either — their carried rule is hex validity only, which
// is what their empty extra rule lists in catalog.json record. Adding a real
// floor means theme-check gains the assertion first, then the catalog rules
// lists and this package grow together (GDK-786 hand-off).
//
// Input defense (GDK-769 axis 3): unknown token names are IGNORED with a
// warn-severity violation — a stale schema (a token renamed or removed in a
// newer catalog) must never panic or brick a config write. Malicious or
// corrupt values (huge strings, non-color payloads, truncated hex) are
// rejected as invalid hex; echoed values are truncated so an error message
// cannot be turned into a paste bomb.
package tokencheck

